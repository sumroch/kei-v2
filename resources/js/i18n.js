function lookup(locale, key) {
    return key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), messages[locale]);
}

export function useT() {
    const page = usePage();

    return (key, params = {}) => {
        const locale = page.props.locale === 'en' ? 'en' : 'ja';
        const text = lookup(locale, key) ?? lookup('ja', key) ?? key;

        return String(text).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
    };
}
